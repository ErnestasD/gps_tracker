/** Geodesic circle ring for map rendering. */
export function circleRing(center: LngLat, radiusM: number, steps = 64): LngLat[] {
  const [lon, lat] = center;
  const R = 6371000;
  const d = radiusM / R;
  const f1 = (lat * Math.PI) / 180;
  const l1 = (lon * Math.PI) / 180;
  const ring: LngLat[] = [];
  for (let i = 0; i <= steps; i++) {
    const th = (i / steps) * 2 * Math.PI;
    const f2 = Math.asin(Math.sin(f1) * Math.cos(d) + Math.cos(f1) * Math.sin(d) * Math.cos(th));
    const l2 = l1 + Math.atan2(Math.sin(th) * Math.sin(d) * Math.cos(f1), Math.cos(d) - Math.sin(f1) * Math.sin(f2));
    ring.push([(l2 * 180) / Math.PI, (f2 * 180) / Math.PI]);
  }
  return ring;
}

/** A contiguous slice of a route, wrapped modulo its length — handy for per-trip paths. */
export function routeSlice(route: LngLat[], startIdx: number, count: number): LngLat[] {
  const out: LngLat[] = [];
  for (let i = 0; i < count; i++) out.push(route[(startIdx + i) % route.length]);
  return out;
}

